import type { UnitInput, UnitSource } from "./UnitSource";
import type { Absorb, HP, Mana, Prediction } from "./Resources";
import type { ClassSource, SpecSource } from "./UnitInfo";
import type { GroupScope, GroupMembers, PartyMembers, RaidMembers } from "./GroupMembers";
import type { GroupRoster } from "./GroupRoster";
import type { Buffs, Debuffs } from "./Auras";
import type { KnownSpells } from "./KnownSpells";
import type { SpellSource } from "./SpellSource";
import type { TotemTimer } from "./TotemTimer";
import type { NativeDuration, TimerSource } from "./TimerSource";
import type { SpellCooldown, GlobalCooldown } from "./SpellCooldown";
import type { ManaRegenTimer } from "./ManaRegenTimer";
import type { CastTimer } from "./CastTimer";
import type { TextureSource } from "./TextureSource";
import type { SwingHand, SwingTimer } from "./SwingTimer";
import type { AuraTimer, AuraTimerOptions } from "./AuraTimer";
import type { EditModeLayouts } from "./EditModeLayouts";
import type { SourceConverter, ValueSource } from "./SourceConverter";
import type { NativeNumberSource } from "./NativeNumberSource";
import { openSource } from "./Source";

export function UseSource(source: typeof HP, unit?: UnitInput): HP;
export function UseSource(source: typeof Absorb, unit: UnitInput): Absorb;
export function UseSource(source: typeof Prediction, unit: UnitInput): Prediction;
export function UseSource(source: typeof Mana, unit: UnitInput): Mana;
export function UseSource(source: typeof UnitSource, token: string): UnitSource;
export function UseSource(source: typeof ClassSource, unit: UnitInput): ClassSource;
export function UseSource(source: typeof SpecSource, unit: UnitInput): SpecSource;
export function UseSource(source: typeof GroupMembers, scope?: GroupScope): GroupMembers;
export function UseSource(source: typeof PartyMembers): PartyMembers;
export function UseSource(source: typeof RaidMembers): RaidMembers;
export function UseSource(source: typeof GroupRoster, scope?: GroupScope, options?: { pets?: boolean; includeSelfWhenSolo?: boolean }): GroupRoster;
export function UseSource(source: typeof Buffs, unit: UnitInput): Buffs;
export function UseSource(source: typeof Debuffs, unit: UnitInput): Debuffs;
export function UseSource(source: typeof KnownSpells): KnownSpells;
export function UseSource(source: typeof SpellSource, spellId: number): SpellSource;
export function UseSource(source: typeof TotemTimer, spell: number | string): TotemTimer;
export function UseSource(source: typeof TimerSource, read: () => NativeDuration | undefined, events: readonly string[], unit?: string): TimerSource;
export function UseSource(source: typeof SpellCooldown, spellId: number | string, options?: { ignoreGCD?: boolean }): SpellCooldown;
export function UseSource(source: typeof GlobalCooldown): GlobalCooldown;
export function UseSource(source: typeof ManaRegenTimer, observe: (listener: (event: string, payload: unknown[], value: number) => void) => () => void): ManaRegenTimer;
export function UseSource(source: typeof CastTimer, unit?: UnitInput): CastTimer;
export function UseSource(source: typeof TextureSource, read: () => string | number | undefined, events: readonly string[], unit?: string): TextureSource;
export function UseSource(source: typeof SwingTimer, hand?: SwingHand): SwingTimer;
export function UseSource(source: typeof AuraTimer, unit: UnitInput, options: AuraTimerOptions): AuraTimer;
export function UseSource(source: typeof EditModeLayouts): EditModeLayouts;
export function UseSource<TInput, TOutput>(source: typeof SourceConverter, input: ValueSource<TInput>, convert: (value: TInput) => TOutput): SourceConverter<TInput, TOutput>;
export function UseSource(source: typeof NativeNumberSource, read: () => number): NativeNumberSource;
export function UseSource(source: { prototype: unknown }, ...props: unknown[]): unknown {
    return openSource(source as Function, props);
}
